function zhCountry(country?: string, countryCode?: string): string | undefined {
  if (countryCode) {
    const hit = COUNTRY_BY_CODE[countryCode.toUpperCase()];
    if (hit) return hit;
  }
  if (country) {
    const hit = COUNTRY_BY_NAME[country.trim().toLowerCase()];
    if (hit) return hit;
    return country;
  }
  return undefined;
}

function zhCity(city?: string): string | undefined {
  if (!city) return undefined;
  const key = city.trim().toLowerCase().replace(/\s+city$/, '');
  return CITY_ZH[key] ?? city;
}

/** "台北，台湾" — falls back to the original English text when unknown. */
export function zhLocation(city?: string, country?: string, countryCode?: string): string {
  return [zhCity(city), zhCountry(country, countryCode)].filter(Boolean).join('，') || '报告位置';
}
